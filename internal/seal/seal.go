// Package seal: 루트 키(Root Key) 보호. Seal 인터페이스와 구현체를 담는다.
package seal

// Seal은 "루트 키를 어떻게 안전하게 보관하고, 필요할 때 어떻게 꺼내오는가"를
// 추상화한 인터페이스(interface)다.
//
// Go의 인터페이스는 "이런 메서드들을 가진 타입이라면 무엇이든 이 계약을 만족한다"는
// 약속이다. 다른 언어처럼 "class DevSeal implements Seal"이라고 명시적으로 선언할
// 필요가 없다 — 구조체가 인터페이스에 정의된 메서드를 전부 구현하고 있으면, Go
// 컴파일러가 자동으로 "이 타입은 Seal이다"라고 인정한다 (구조적 타이핑/덕 타이핑).
//
// 이렇게 인터페이스로 분리해두는 이유는 교체 가능성이다. KMS의 나머지 코드(keys,
// barrier 등)는 "Seal이 구체적으로 뭔지는 몰라도, Unseal()을 부르면 32바이트
// Root Key를 돌려준다"는 사실만 알고 동작하면 된다. 그 키가 개발용 패스프레이즈
// (DevSeal)에서 나오는지, Shamir 비밀 분산에서 나오는지, K8s Secret이나 외부
// 클라우드 KMS에서 나오는지는 몰라도 상관없다 — 나중에 구현체만 바꿔 끼우면
// 나머지 코드는 한 줄도 손댈 필요가 없다.
type Seal interface {
	// Unseal은 봉인을 해제해 Root Key(32바이트)를 반환한다.
	// 실패 시(설정 미비, 인증/복호화 실패 등) 에러를 반환한다.
	Unseal() ([]byte, error)

	// Type은 이 seal 구현의 이름을 반환한다 (예: "dev", "shamir", "k8s").
	// 로그나 상태 조회 API에서 "지금 어떤 방식으로 Root Key를 보호하고 있는지"
	// 보여줄 때 쓴다.
	Type() string

	// IsConfigured는 Unseal을 호출했을 때 성공할 가능성이 있는 상태인지 —
	// 즉 이 seal에 필요한 설정(패스프레이즈, 키 조각, 클라우드 자격증명 등)이
	// 갖춰져 있는지를 나타낸다. Unseal의 성공을 보장하진 않지만, "설정이 안
	// 됐으니 시도할 필요도 없다"를 빠르게 판단하는 데 쓴다.
	IsConfigured() bool
}
