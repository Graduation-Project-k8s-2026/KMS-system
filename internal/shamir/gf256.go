// Package shamir: Shamir Secret Sharing — 비밀을 parts개의 조각으로 나누고,
// 그중 threshold개만 모이면 원본을 복원할 수 있게 하는 순수 수학 알고리즘.
//
// Root Key를 "어떻게 보호할지"는 internal/seal의 몫이고, 이 패키지는 "비밀을
// 조각내고 다시 합치는 방법"만 안다. 알고리즘과 그 활용을 분리해두면 이
// 패키지만 독립적으로(다른 구현체와의 교차검증 포함) 검증할 수 있고, 나중에
// Root Key가 아닌 다른 비밀에도 그대로 재사용할 수 있다.
package shamir

import "errors"

// gf256.go: GF(256) 유한체 산술.
//
// 왜 유한체가 필요한가:
// Shamir의 핵심 아이디어는 "차수 threshold-1인 다항식을 하나 그리고, 그 위의
// 점 parts개를 나눠준다. threshold개의 점만 모이면 다항식을 유일하게 복원할
// 수 있다(다항식 보간)"는 것이다. 이걸 실수(real number) 위에서 하면 계수가
// 한없이 커지거나 정밀도가 깨질 수 있고, 그냥 정수(0~255) 위에서 하면 곱셈/
// 나눗셈 결과가 원래 범위를 벗어나 버린다(예: 200*200은 한 바이트에 안 들어감).
//
// GF(256)(= GF(2^8), 원소가 정확히 256개인 유한체)을 쓰면 이 문제가 사라진다:
// 이 체 위의 덧셈/뺄셈/곱셈/나눗셈 결과는 항상 다시 0~255 범위 안의 값이
// 된다("닫혀있다"). 그리고 한 바이트 = 이 체의 원소 하나이므로, 비밀의 바이트
// 하나하나를 "그 바이트 값을 상수항(절편)으로 갖는 다항식"으로 놓고 이 체
// 위에서 다항식 보간을 하면 된다. AES를 포함한 여러 암호 표준이 쓰는 것과
// 같은 체 — 기약다항식(irreducible polynomial) x^8+x^4+x^3+x+1(16진수로
// 표현하면 0x11B, 최상위 비트를 뗀 리덕션 값은 0x1B) — 를 그대로 쓴다.
// HashiCorp Vault의 shamir 패키지도 같은 체를 쓰므로, 이 선택이 곧 두 구현이
// 조각을 서로 교환해 쓸 수 있는(interoperable) 전제 조건이다.

// Add는 GF(2^8)에서 a+b를 계산한다.
//
// GF(2^8)는 "characteristic 2" 체다 — 즉 자기 자신을 두 번 더하면 항상 0이
// 된다(a+a=0). 그래서 덧셈과 뺄셈이 완전히 같은 연산이 되고, 둘 다 XOR
// 한 번으로 끝난다: 자리올림(carry)이 없는 "비트별 독립적인" 덧셈이기 때문이다.
func Add(a, b byte) byte {
	return a ^ b
}

// Sub는 GF(2^8)에서 a-b를 계산한다. 위에서 설명했듯 이 체에서는 덧셈과
// 뺄셈이 같은 연산이므로 Add와 동일하다.
func Sub(a, b byte) byte {
	return a ^ b
}

// Mul은 GF(2^8) 위에서 a*b를 계산한다("다항식으로서 곱한 뒤, 결과가 8차를
// 넘으면 기약다항식으로 나눈 나머지를 취한다"는 정의를 "Russian peasant
// multiplication"이라는 반복적인 방법으로 구현한 것).
//
// 왜 로그/지수 테이블 대신 이렇게 구현했는가(constant-time):
// 흔한 GF(256) 곱셈 구현은 "로그 테이블로 지수를 찾고, 지수를 더한 뒤, 지수
// 테이블로 다시 값을 찾는" 방식을 쓴다. 이때 테이블을 "비밀 바이트 값 그
// 자체"로 인덱싱하게 되는데, 이 인덱싱에 걸리는 시간이나 CPU 캐시 접근
// 패턴이 인덱스(=비밀 값)에 따라 미세하게 달라질 수 있다. 만약 공격자가 이
// KMS 서버에 정밀하게 반복 요청을 보내며 응답 시간을 측정할 수 있는 위치에
// 있다면, 이런 미세한 시간 차이를 통계적으로 누적해 비밀 조각의 값을 바이트
// 단위로 추측해낼 수 있다 — 이런 공격을 타이밍 사이드채널 공격이라 부른다.
//
// 아래 구현은 테이블 조회나 "비밀 값에 따라 분기(if)하는" 코드가 전혀 없다.
// 대신 "이 비트가 서 있으면 결과에 더하고, 아니면 안 더한다"는 판단을
// if 문이 아니라 "0xFF 아니면 0x00"인 비트마스크를 만들어서 AND로 표현한다
// — 그래서 b의 값이 무엇이든 실행되는 연산의 종류와 횟수가 항상 똑같다
// (8회 고정 반복, 매 반복마다 항상 같은 연산).
func Mul(a, b byte) byte {
	var result byte
	for i := 0; i < 8; i++ {
		// b의 최하위 비트가 1이면 0xFF, 0이면 0x00이 되는 마스크.
		// (부호 없는 정수에 대한 단항 -는 2의 보수 규칙에 따라
		// 0 -> 0x00, 1 -> 0xFF를 만들어낸다.)
		mask := -(b & 1)
		result ^= a & mask

		// a에 x를 곱하는 것(=한 비트 왼쪽 시프트)과 같다. 시프트 전에 최상위
		// 비트가 서 있었다면(=결과가 8비트를 넘친다면) 기약다항식 0x1B로
		// 리덕션해야 하는데, 이것도 if 대신 마스크로 표현한다.
		carry := -(a >> 7)
		a = (a << 1) ^ (carry & 0x1B)

		b >>= 1
	}
	return result
}

// Inv는 GF(2^8)에서 a의 곱셈 역원(a * Inv(a) == 1)을 계산한다. a==0의
// 역원은 정의되지 않는다 — 0으로 나누기와 같은 문제이며, 호출부인 Div가
// 이 경우를 따로 처리한다.
//
// GF(2^8)\{0}은 크기 255(=2^8-1)인 곱셈군이다. 유한군의 라그랑주 정리에
// 의해 이 군의 모든 원소 a는 a^255 == 1을 만족하므로, a^254 == a^-1이다.
// 아래는 a^254를 "제곱과 곱셈을 고정된 순서로 10번" 실행해서 구하는
// 덧셈 사슬(addition chain)이다. 지수 254는 코드에 고정된 상수이므로 이
// 계산 순서 자체가 비밀 값 a에 따라 달라지지 않는다(constant-time) —
// 즉 Inv도 Mul과 마찬가지로 타이밍 사이드채널에서 안전하다.
func Inv(a byte) byte {
	b := Mul(a, a)   // a^2
	c := Mul(a, b)   // a^3
	b = Mul(c, c)    // a^6
	b = Mul(b, b)    // a^12
	c = Mul(b, c)    // a^15
	b = Mul(b, b)    // a^24
	b = Mul(b, b)    // a^48
	b = Mul(b, c)    // a^63
	b = Mul(b, b)    // a^126
	b = Mul(a, b)    // a^127
	return Mul(b, b) // a^254 == a^-1
}

// ErrDivideByZero: Div(a, 0)을 호출했을 때 반환. GF(2^8)에서 0으로 나누는
// 것은 정의되지 않는다.
var ErrDivideByZero = errors.New("shamir: division by zero in GF(256)")

// Div는 GF(2^8)에서 a/b(= a * Inv(b))를 계산한다.
func Div(a, b byte) (byte, error) {
	if b == 0 {
		return 0, ErrDivideByZero
	}
	return Mul(a, Inv(b)), nil
}
